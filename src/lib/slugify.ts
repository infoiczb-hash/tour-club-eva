export function slugify(str: string): string {
  if (!str) return "";

  const ru: { [key: string]: string } = {
    'а': 'a', 'б': 'b', 'в': 'v', 'г': 'g', 'д': 'd', 
    'е': 'e', 'ё': 'yo', 'ж': 'zh', 'з': 'z', 'и': 'i', 
    'й': 'y', 'к': 'k', 'л': 'l', 'м': 'm', 'н': 'n', 
    'о': 'o', 'п': 'p', 'р': 'r', 'с': 's', 'т': 't', 
    'у': 'u', 'ф': 'f', 'х': 'h', 'ц': 'ts', 'ч': 'ch', 
    'ш': 'sh', 'щ': 'sch', 'ъ': '', 'ы': 'y', 'ь': '', 
    'э': 'e', 'ю': 'yu', 'я': 'ya'
  };

  return str
    .toLowerCase()
    .split('')
    .map(char => ru[char] || char) // Заменяем русские буквы
    .join('')
    .replace(/[^\w\s-]/g, '') // Убираем спецсимволы (кроме букв, цифр, пробела и дефиса)
    .replace(/\s+/g, '-')     // Меняем пробелы на дефисы
    .replace(/-+/g, '-')      // Убираем дублирующиеся дефисы
    .replace(/^-+|-+$/g, ''); // Убираем дефисы в начале и конце
}